const fs = require("fs");
const path = require("path");
const crypto = require("crypto");
const multer = require("multer");

const UPLOAD_ROOT = process.env.UPLOAD_DIR
  ? path.resolve(process.env.UPLOAD_DIR)
  : path.join(__dirname, "..", "..", "uploads");
const SCENARIO_DIR = path.join(UPLOAD_ROOT, "scenarios");
const MAX_IMAGE_BYTES = 8 * 1024 * 1024;

fs.mkdirSync(SCENARIO_DIR, { recursive: true });

// The client-supplied mimetype/extension cannot be trusted, so the real type is sniffed
// from the file's first bytes and only these formats are accepted.
const detectImageType = (buf) => {
  if (buf.length >= 3 && buf[0] === 0xff && buf[1] === 0xd8 && buf[2] === 0xff) return "jpg";
  if (
    buf.length >= 8 &&
    buf.subarray(0, 8).equals(Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]))
  )
    return "png";
  if (
    buf.length >= 12 &&
    buf.subarray(0, 4).toString("ascii") === "RIFF" &&
    buf.subarray(8, 12).toString("ascii") === "WEBP"
  )
    return "webp";
  return null;
};

const upload = multer({
  storage: multer.memoryStorage(),
  limits: { fileSize: MAX_IMAGE_BYTES, files: 1 },
});

/**
 * Validates an uploaded multer file and writes it under a random name.
 * Returns { url, storedFile } or throws an Error with `.status` set.
 */
const saveScenarioImage = async (file) => {
  if (!file) {
    const err = new Error("Image file is required (field name: image)");
    err.status = 400;
    throw err;
  }

  const type = detectImageType(file.buffer);
  if (!type) {
    const err = new Error("Only JPEG, PNG or WebP images are allowed");
    err.status = 400;
    throw err;
  }

  const storedFile = `${crypto.randomBytes(16).toString("hex")}.${type}`;
  await fs.promises.writeFile(path.join(SCENARIO_DIR, storedFile), file.buffer);

  return { url: `/uploads/scenarios/${storedFile}`, storedFile };
};

const deleteStoredFile = async (storedFile) => {
  // storedFile is generated by saveScenarioImage; the basename check is defence in depth.
  if (!storedFile || storedFile !== path.basename(storedFile)) return;
  try {
    await fs.promises.unlink(path.join(SCENARIO_DIR, storedFile));
  } catch (err) {
    if (err.code !== "ENOENT") throw err;
  }
};

module.exports = {
  UPLOAD_ROOT,
  MAX_IMAGE_BYTES,
  upload,
  saveScenarioImage,
  deleteStoredFile,
};
